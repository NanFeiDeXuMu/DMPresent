"use strict";
/* Interactive companion to the Group 24 poster. No dependencies: every chart is plain SVG.
   Data lives in /data/*.json and is generated by scripts/build_data.py. */

const NS = "http://www.w3.org/2000/svg";
const C = { ink: "#1b1b1b", ink2: "#45433e", muted: "#6b6862", paper: "#faf8f3", hair: "#d8d3c8",
  light: "#ece8df", gray: "#b3afa6", yellow: "#f5c400", yellowSoft: "#f7e3a1", amber: "#b07a00" };
const CLASSES = ["#ece7da", "#f7e3a1", "#f5c400", "#b07a00", "#1b1b1b"];
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

const fmt = {
  int: v => Math.round(v).toLocaleString("en-US"),
  pct0: v => (v * 100).toFixed(0) + "%",
  pct1: v => (v * 100).toFixed(1) + "%",
  pct2: v => (v * 100).toFixed(2) + "%",
  pct: v => v <= 0 ? "0%" : v < 1e-4 ? "< 0.01%" : v < 1e-3 ? (v * 100).toFixed(3) + "%"
    : v < 0.01 ? (v * 100).toFixed(2) + "%" : (v * 100).toFixed(1) + "%",
  f1: v => v.toFixed(1),
  f2: v => v.toFixed(2),
  x1: v => v.toFixed(1) + "×",
  hh: v => String(v).padStart(2, "0") + ":00",
  short: v => String(v).slice(0, 7),
  k: v => (v / 1000).toFixed(v >= 10000 ? 0 : 1) + "k",
};

function el(tag, attrs = {}, parent = null, text = null) {
  const node = document.createElementNS(NS, tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  if (text !== null) node.textContent = text;
  if (parent) parent.appendChild(node);
  return node;
}
function h(tag, attrs = {}, html = "") {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  node.innerHTML = html;
  return node;
}
const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const classOf = (v, edges) => edges.filter(e => v >= e).length;

/* Tooltip */
const tip = document.getElementById("tooltip");
function showTip(html, ev) {
  tip.innerHTML = html;
  tip.hidden = false;
  const pad = 14, r = tip.getBoundingClientRect();
  let x = ev.clientX + pad, y = ev.clientY + pad;
  if (x + r.width > innerWidth - 8) x = ev.clientX - r.width - pad;
  if (y + r.height > innerHeight - 8) y = ev.clientY - r.height - pad;
  tip.style.left = x + "px";
  tip.style.top = y + "px";
}
const hideTip = () => { tip.hidden = true; };

function segmented(container, attr, onChange) {
  const buttons = [...container.querySelectorAll("button")];
  buttons.forEach(b => b.addEventListener("click", () => {
    buttons.forEach(o => o.setAttribute("aria-checked", String(o === b)));
    onChange(b.dataset[attr]);
  }));
}

function bindValues(data) {
  document.querySelectorAll("[data-v]").forEach(node => {
    const [path, f] = node.dataset.v.split("|");
    const value = path.split(".").reduce((o, k) => o?.[k], data);
    if (value !== undefined) node.textContent = f ? fmt[f](value) : value;
  });
}

/* Funnel */
function renderFunnel(s) {
  const steps = [
    [fmt.int(s.raw_records), "raw trip records"],
    [fmt.int(s.clean_records), `cleaned trips · ${fmt.pct2(s.retention)} kept`],
    [fmt.int(s.unique_baskets), `weighted baskets (${Math.round(s.clean_records / s.unique_baskets)}× fewer)`],
    [fmt.int(s.rules), "directional rules mined"],
    ["4", "rules highlighted, each recounted"],
  ];
  const ol = document.getElementById("funnel");
  steps.forEach(([n, l]) => ol.appendChild(h("li", {}, `<span class="n">${n}</span><span class="l">${l}</span>`)));
}

/* Map */
function renderMap(Z, summary) {
  const svg = document.getElementById("map");
  svg.setAttribute("viewBox", Z.viewBox.join(" "));
  const zones = new Map(Z.zones.map(z => [z.id, z]));
  const rank = { pickups: new Map(), dropoffs: new Map() };
  for (const m of ["pickups", "dropoffs"]) {
    [...Z.zones].sort((a, b) => b[m] - a[m]).forEach((z, i) => rank[m].set(z.id, i + 1));
  }
  const edges = [1e-4, 1e-3, 1e-2, 3e-2];
  const labels = ["< 0.01%", "0.01–0.1%", "0.1–1%", "1–3%", "≥ 3%"];
  document.getElementById("map-legend").innerHTML =
    "<span><b>Share of all trips</b></span>" +
    CLASSES.map((c, i) => `<span><i style="background:${c}"></i>${labels[i]}</span>`).join("");
  const paths = new Map();
  for (const z of Z.zones) {
    if (!z.d) continue;
    const p = el("path", { d: z.d, class: "zone", "data-id": z.id }, svg);
    paths.set(z.id, p);
  }
  // Borough labels at the centre of their zones' bounding boxes.
  const labelLayer = el("g", { "pointer-events": "none" }, svg);
  const boroughBoxes = {};
  for (const z of Z.zones) {
    const p = paths.get(z.id);
    if (!p) continue;
    const b = p.getBBox();
    const acc = boroughBoxes[z.borough] ??= [Infinity, Infinity, -Infinity, -Infinity];
    acc[0] = Math.min(acc[0], b.x); acc[1] = Math.min(acc[1], b.y);
    acc[2] = Math.max(acc[2], b.x + b.width); acc[3] = Math.max(acc[3], b.y + b.height);
  }
  const offsets = { Manhattan: [-95, -40], Bronx: [10, 0], Queens: [70, -110], Brooklyn: [-10, 20], "Staten Island": [0, 0] };
  for (const [name, [x0, y0, x1, y1]] of Object.entries(boroughBoxes)) {
    const [dx, dy] = offsets[name] ?? [0, 0];
    el("text", { x: (x0 + x1) / 2 + dx, y: (y0 + y1) / 2 + dy, "text-anchor": "middle", "font-size": 15,
      "font-weight": 600, "letter-spacing": ".08em", fill: C.ink2, stroke: C.paper, "stroke-width": 4,
      "paint-order": "stroke" }, labelLayer, name.toUpperCase());
  }

  let metric = "pickups", selected = summary.top_pickup_zone.zone_id;
  const recolor = () => {
    for (const [id, p] of paths) p.setAttribute("fill", CLASSES[classOf(zones.get(id)[metric] / Z.total, edges)]);
  };
  const select = document.getElementById("zone-select");
  [...Z.zones].sort((a, b) => a.name.localeCompare(b.name)).forEach(z =>
    select.appendChild(new Option(`${z.name} (${z.borough})`, z.id)));

  const panel = document.getElementById("zone-panel");
  function linkList(title, list, total, verb) {
    if (!list.length) return "";
    const max = list[0][1];
    return `<div class="links"><h4>${title}</h4><ol>` + list.map(([id, n]) => {
      const z = zones.get(id);
      return `<li data-id="${id}" tabindex="0"><span class="name">${esc(z ? z.name : "Zone " + id)}</span>` +
        `<span class="v">${fmt.int(n)} · ${fmt.pct1(n / total)}</span>` +
        `<span class="bar"><i style="width:${(n / max * 100).toFixed(1)}%"></i></span></li>`;
    }).join("") + `</ol></div>`;
  }
  function choose(id) {
    selected = id;
    const z = zones.get(id);
    select.value = id;
    for (const p of paths.values()) p.classList.remove("sel", "dest");
    const dests = (metric === "pickups" ? z.to : z.from).map(([d]) => d).filter(d => d !== id);
    dests.forEach(d => { const p = paths.get(d); if (p) { p.classList.add("dest"); svg.insertBefore(p, labelLayer); } });
    const sp = paths.get(id);
    if (sp) { sp.classList.add("sel"); svg.insertBefore(sp, labelLayer); }
    panel.innerHTML =
      `<h3>${esc(z.name)}</h3><p class="sub">${esc(z.borough)} · zone ${z.id}${sp ? "" : " · not drawn on the map"}</p>` +
      `<div class="stats">` +
      `<div><b>${fmt.int(z.pickups)}</b><span>pickups · ${fmt.pct(z.pickups / Z.total)} · rank ${rank.pickups.get(id)}</span></div>` +
      `<div><b>${fmt.int(z.dropoffs)}</b><span>drop-offs · ${fmt.pct(z.dropoffs / Z.total)} · rank ${rank.dropoffs.get(id)}</span></div>` +
      `</div>` +
      linkList("Where its pickups go", z.to, z.pickups) +
      linkList("Where its drop-offs came from", z.from, z.dropoffs) +
      `<p class="note">Percentages in the lists are shares of this zone's pickups or drop-offs. Dashed outlines on the map mark the top ${metric === "pickups" ? "destinations" : "origins"}.</p>`;
    panel.querySelectorAll("li[data-id]").forEach(li => {
      const go = () => choose(+li.dataset.id);
      li.addEventListener("click", go);
      li.addEventListener("keydown", e => { if (e.key === "Enter") go(); });
    });
  }
  svg.addEventListener("pointermove", ev => {
    const p = ev.target.closest("path.zone");
    if (!p) return hideTip();
    const z = zones.get(+p.dataset.id);
    showTip(`<b>${esc(z.name)}</b><br>${esc(z.borough)}<br>Pickups ${fmt.int(z.pickups)} (${fmt.pct(z.pickups / Z.total)})` +
      `<br>Drop-offs ${fmt.int(z.dropoffs)} (${fmt.pct(z.dropoffs / Z.total)})`, ev);
  });
  svg.addEventListener("pointerleave", hideTip);
  svg.addEventListener("click", ev => { const p = ev.target.closest("path.zone"); if (p) choose(+p.dataset.id); });
  select.addEventListener("change", () => choose(+select.value));
  segmented(document.querySelector("#where .seg"), "metric", m => { metric = m; recolor(); choose(selected); });
  recolor();
  choose(selected);
}

/* Borough matrix */
function renderMatrix(B) {
  const svg = document.getElementById("matrix");
  const n = B.order.length, M = B.matrix;
  const rowSum = M.map(r => r.reduce((a, b) => a + b, 0));
  const colSum = B.order.map((_, j) => M.reduce((a, r) => a + r[j], 0));
  const cell = 92, left = 128, top = 56;
  function draw(mode) {
    svg.replaceChildren();
    const extraRow = mode === "row", extraCol = mode === "col";
    const rows = n + (extraRow ? 1 : 0), cols = n + (extraCol ? 1 : 0);
    svg.setAttribute("viewBox", `0 0 ${left + cols * cell + 8} ${top + rows * cell + 8}`);
    const edges = mode === "all" ? [1e-4, 1e-3, 1e-2, 0.1] : [0.01, 0.05, 0.2, 0.5];
    el("text", { x: left, y: 16, "font-size": 13, fill: C.muted }, svg, "Drop-off borough →");
    el("text", { x: 0, y: top - 8, "font-size": 13, fill: C.muted }, svg, "Pickup borough ↓");
    const colNames = [...B.order, ...(extraCol ? ["All drop-offs"] : [])];
    const rowNames = [...B.order, ...(extraRow ? ["All pickups"] : [])];
    colNames.forEach((name, j) => el("text", { x: left + j * cell + cell / 2, y: top - 12, "text-anchor": "middle",
      "font-size": 12.5, "font-weight": 600, fill: C.ink }, svg, name));
    rowNames.forEach((name, i) => el("text", { x: left - 10, y: top + i * cell + cell / 2 + 4, "text-anchor": "end",
      "font-size": 12.5, "font-weight": 600, fill: C.ink }, svg, name));
    for (let i = 0; i < rows; i++) {
      for (let j = 0; j < cols; j++) {
        const base = i === n || j === n;
        let count, value, info;
        if (i === n) { count = colSum[j]; value = colSum[j] / B.total; info = `${B.order[j]} share of all drop-offs`; }
        else if (j === n) { count = rowSum[i]; value = rowSum[i] / B.total; info = `${B.order[i]} share of all pickups`; }
        else {
          count = M[i][j];
          value = mode === "all" ? count / B.total : mode === "row" ? count / (rowSum[i] || 1) : count / (colSum[j] || 1);
        }
        const k = classOf(value, edges);
        const g = el("g", {}, svg);
        el("rect", { x: left + j * cell, y: top + i * cell, width: cell, height: cell, class: "cell",
          fill: base ? C.light : CLASSES[k] }, g);
        el("text", { x: left + j * cell + cell / 2, y: top + i * cell + cell / 2 + 5, "text-anchor": "middle",
          "font-size": 15, "font-weight": base ? 500 : 600, fill: !base && k >= 3 ? "#fff" : C.ink,
          "pointer-events": "none" }, g, count === 0 ? "0" : fmt.pct(value));
        g.addEventListener("pointermove", ev => {
          if (base) return showTip(`<b>${info}</b><br>${fmt.int(count)} trips · ${fmt.pct(value)}<br>Baseline for lift`, ev);
          const a = B.order[i], b = B.order[j];
          showTip(`<b>${a} → ${b}</b><br>${fmt.int(count)} trips<br>${fmt.pct(count / B.total)} of all trips` +
            `<br>${fmt.pct(count / (rowSum[i] || 1))} of ${a} pickups<br>${fmt.pct(count / (colSum[j] || 1))} of ${b} drop-offs`, ev);
        });
        g.addEventListener("pointerleave", hideTip);
      }
    }
  }
  segmented(document.querySelector("#flows .seg"), "mode", draw);
  draw("all");
}

/* Generic axes helpers */
function linear(d0, d1, r0, r1) { const f = v => r0 + (v - d0) / (d1 - d0) * (r1 - r0); f.invert = p => d0 + (p - r0) / (r1 - r0) * (d1 - d0); return f; }
function yGrid(svg, y, ticks, x0, x1, label) {
  const g = el("g", { class: "grid" }, svg), a = el("g", { class: "axis" }, svg);
  ticks.forEach(t => {
    el("line", { x1: x0, x2: x1, y1: y(t), y2: y(t) }, g);
    el("text", { x: x0 - 8, y: y(t) + 4, "text-anchor": "end" }, a, label(t));
  });
}

/* Hourly curves */
function renderHourly(T, s) {
  const svg = document.getElementById("hourly");
  const W = 560, H = 300, m = { l: 44, r: 84, t: 16, b: 34 };
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  const wd = T.hourly.weekday.daily_average, we = T.hourly.weekend.daily_average;
  const max = Math.ceil(Math.max(...wd, ...we) / 2000) * 2000;
  const x = linear(0, 23, m.l, W - m.r), y = linear(0, max, H - m.b, m.t);
  yGrid(svg, y, Array.from({ length: max / 2000 + 1 }, (_, i) => i * 2000), m.l, W - m.r, t => t ? t / 1000 + "k" : "0");
  const ax = el("g", { class: "axis" }, svg);
  el("line", { x1: m.l, x2: W - m.r, y1: H - m.b, y2: H - m.b }, ax);
  [0, 6, 12, 18, 23].forEach(t => el("text", { x: x(t), y: H - m.b + 20, "text-anchor": "middle" }, ax, fmt.hh(t)));
  // Yellow area: after-midnight hours where weekends exceed weekdays (crossing interpolated).
  const pts = [];
  for (let i = 0; i < 6; i++) {
    if (we[i] > wd[i]) pts.push([i, wd[i], we[i]]);
    if (i < 5 && (we[i] > wd[i]) !== (we[i + 1] > wd[i + 1])) {
      const t = (wd[i] - we[i]) / ((we[i + 1] - we[i]) - (wd[i + 1] - wd[i]));
      const v = wd[i] + t * (wd[i + 1] - wd[i]);
      pts.push([i + t, v, v]);
    }
  }
  if (pts.length > 1) {
    const d = pts.map(([h, a]) => `${x(h)},${y(a)}`).concat(pts.slice().reverse().map(([h, , b]) => `${x(h)},${y(b)}`));
    el("polygon", { points: d.join(" "), fill: C.yellow }, svg);
  }
  const line = (arr, w, dash) => el("polyline", { points: arr.map((v, i) => `${x(i)},${y(v)}`).join(" "), fill: "none",
    stroke: C.ink, "stroke-width": w, "stroke-dasharray": dash || "none", "stroke-linejoin": "round" }, svg);
  line(wd, 3.2); line(we, 2, "6 4");
  el("text", { x: W - m.r + 8, y: y(wd[23]) + 4, "font-size": 13, "font-weight": 600, fill: C.ink }, svg, "Weekdays");
  el("text", { x: W - m.r + 8, y: y(we[23]) + 4, "font-size": 13, "font-weight": 600, fill: C.ink }, svg, "Weekends");
  const pk = s.peak_hours.weekday.hour;
  el("text", { x: x(pk) - 8, y: y(wd[pk]) - 6, "text-anchor": "end", "font-size": 12.5, fill: C.ink }, svg,
    `Weekday peak ${fmt.hh(pk)} · ${fmt.k(wd[pk])}/day`);
  // Hover guide.
  const guide = el("line", { y1: m.t, y2: H - m.b, stroke: C.ink, "stroke-width": 1, opacity: 0 }, svg);
  const dots = [el("circle", { r: 4.5, fill: C.ink, opacity: 0 }, svg), el("circle", { r: 4.5, fill: C.yellow, stroke: C.ink, opacity: 0 }, svg)];
  const hit = el("rect", { x: m.l, y: m.t, width: W - m.l - m.r, height: H - m.t - m.b, fill: "transparent" }, svg);
  hit.addEventListener("pointermove", ev => {
    const p = svg.createSVGPoint(); p.x = ev.clientX; p.y = ev.clientY;
    const loc = p.matrixTransform(svg.getScreenCTM().inverse());
    const hr = Math.max(0, Math.min(23, Math.round(x.invert(loc.x))));
    guide.setAttribute("x1", x(hr)); guide.setAttribute("x2", x(hr)); guide.setAttribute("opacity", .5);
    [[wd, 0], [we, 1]].forEach(([arr, k]) => { dots[k].setAttribute("cx", x(hr)); dots[k].setAttribute("cy", y(arr[hr])); dots[k].setAttribute("opacity", 1); });
    showTip(`<b>${fmt.hh(hr)}–${String(hr).padStart(2, "0")}:59</b><br>Weekday ${fmt.int(wd[hr])} trips/day<br>Weekend ${fmt.int(we[hr])} trips/day`, ev);
  });
  hit.addEventListener("pointerleave", () => { hideTip(); guide.setAttribute("opacity", 0); dots.forEach(d => d.setAttribute("opacity", 0)); });
}

/* Daily bars */
function renderDaily(T) {
  const svg = document.getElementById("daily");
  const W = 560, H = 300, m = { l: 44, r: 8, t: 16, b: 34 };
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  const days = T.daily.map(([d, n]) => ({ date: new Date(d + "T12:00:00"), n }));
  const max = Math.ceil(Math.max(...days.map(d => d.n)) / 20000) * 20000;
  const y = linear(0, max, H - m.b, m.t), bw = (W - m.l - m.r) / days.length;
  yGrid(svg, y, Array.from({ length: max / 20000 + 1 }, (_, i) => i * 20000), m.l, W - m.r, t => t ? t / 1000 + "k" : "0");
  const ax = el("g", { class: "axis" }, svg);
  days.forEach((d, i) => {
    const wkend = d.date.getDay() === 0 || d.date.getDay() === 6;
    const r = el("rect", { x: m.l + i * bw + 1.5, y: y(d.n), width: bw - 3, height: y(0) - y(d.n),
      fill: wkend ? C.yellow : C.gray }, svg);
    r.addEventListener("pointermove", ev => showTip(`<b>${DAYS[d.date.getDay()]} ${d.date.getDate()} ${MONTHS[d.date.getMonth()]}</b><br>${fmt.int(d.n)} trips`, ev));
    r.addEventListener("pointerleave", hideTip);
    if ([1, 5, 10, 15, 20, 25, 31].includes(d.date.getDate()))
      el("text", { x: m.l + i * bw + bw / 2, y: H - m.b + 20, "text-anchor": "middle" }, ax, `${d.date.getDate()} Jan`);
  });
  el("line", { x1: m.l, x2: W - m.r, y1: H - m.b, y2: H - m.b }, ax);
}

