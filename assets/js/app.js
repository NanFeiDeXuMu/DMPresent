function renderExplorer(R) {
  const N = R.N;
  const rules = R.rules.map(r => ({ a: r[0], c: r[1], n11: r[2], nA: r[3], nB: r[4], confidence: r[5], lift: r[6],
    kulc: r[7], ir: r[8], support: r[2] / N,
    text: [...r[0], ...r[1]].map(id => (R.items[id][0] + ": " + R.items[id][1]).toLowerCase()) }));
  const $ = id => document.getElementById(id);
  const fields = [...new Set(R.items.map(i => i[0]))];
  fields.forEach(f => $("f-field").appendChild(new Option(f, f)));
  let page = 0, filtered = [], active = null;
  const PER = 12;
  function apply() {
    const terms = $("f-text").value.toLowerCase().split(",").map(t => t.trim()).filter(Boolean);
    const field = $("f-field").value, sup = +$("f-sup").value / 100, conf = +$("f-conf").value / 100, lift = +$("f-lift").value;
    const key = $("f-sort").value;
    $("o-sup").textContent = (+$("f-sup").value).toFixed(1) + "%";
    $("o-conf").textContent = $("f-conf").value + "%";
    $("o-lift").textContent = (+$("f-lift").value).toFixed(2);
    filtered = rules.filter(r => r.support >= sup - 1e-12 && r.confidence >= conf - 1e-12 && r.lift >= lift - 1e-12
      && (!field || r.c.some(id => R.items[id][0] === field))
      && terms.every(t => r.text.some(s => s.includes(t))))
      .sort((p, q) => q[key] - p[key] || q.lift - p.lift || q.support - p.support);
    page = 0;
    draw();
  }
  function draw() {
    const pages = Math.max(1, Math.ceil(filtered.length / PER));
    page = Math.min(page, pages - 1);
    $("rule-count").textContent = `${fmt.int(filtered.length)} of ${fmt.int(rules.length)} rules match`;
    $("page").textContent = `Page ${page + 1} of ${pages}`;
    $("prev").disabled = page === 0;
    $("next").disabled = page >= pages - 1;
    const body = $("rule-rows");
    body.replaceChildren();
    filtered.slice(page * PER, page * PER + PER).forEach(r => {
      const tr = h("tr", { tabindex: "0" },
        `<td>${r.a.map(id => itemHTML(R, id)).join("")}</td><td>${r.c.map(id => itemHTML(R, id)).join("")}</td>` +
        `<td class="num">${fmt.pct2(r.support)}</td><td class="num">${fmt.pct1(r.confidence)}</td>` +
        `<td class="num">${r.lift.toFixed(2)}</td><td class="num">${r.kulc.toFixed(3)}</td><td class="num">${r.ir.toFixed(3)}</td>`);
      if (r === active) tr.classList.add("on");
      const open = () => { active = r; detail(r); draw(); };
      tr.addEventListener("click", open);
      tr.addEventListener("keydown", e => { if (e.key === "Enter") open(); });
      body.appendChild(tr);
    });
    if (!filtered.length) body.appendChild(h("tr", {}, `<td colspan="7">No rule matches these filters.</td>`));
  }
  function detail(r) {
    const n10 = r.nA - r.n11, n01 = r.nB - r.n11, n00 = N - r.nA - r.nB + r.n11;
    const A = r.a.map(id => itemHTML(R, id)).join(""), B = r.c.map(id => itemHTML(R, id)).join("");
    $("rule-detail").innerHTML = `<div class="detail-grid"><div>
      <table class="ct"><tr><th></th><th>B</th><th>not B</th><th>Total</th></tr>
      <tr><th>A</th><td class="hit">${fmt.int(r.n11)}</td><td>${fmt.int(n10)}</td><td>${fmt.int(r.nA)}</td></tr>
      <tr><th>not A</th><td>${fmt.int(n01)}</td><td>${fmt.int(n00)}</td><td>${fmt.int(N - r.nA)}</td></tr>
      <tr><th>Total</th><td>${fmt.int(r.nB)}</td><td>${fmt.int(N - r.nB)}</td><td>${fmt.int(N)}</td></tr></table></div>
      <div class="calc"><p><b>A</b> ${A} <b>B</b> ${B}</p>
      <p><code>support = ${fmt.int(r.n11)} / ${fmt.int(N)} = ${fmt.pct2(r.support)}</code></p>
      <p><code>confidence = ${fmt.int(r.n11)} / ${fmt.int(r.nA)} = ${fmt.pct1(r.confidence)}</code></p>
      <p><code>P(B) = ${fmt.int(r.nB)} / ${fmt.int(N)} = ${fmt.pct1(r.nB / N)}; lift = ${fmt.pct1(r.confidence)} / ${fmt.pct1(r.nB / N)} = ${r.lift.toFixed(2)}</code></p>
      <p><code>reverse confidence = ${fmt.int(r.n11)} / ${fmt.int(r.nB)} = ${fmt.pct1(r.n11 / r.nB)}; Kulc = ${r.kulc.toFixed(3)}; IR = ${r.ir.toFixed(3)}</code></p>
      </div></div>`;
  }
  ["f-text", "f-field", "f-sup", "f-conf", "f-lift", "f-sort"].forEach(id => $(id).addEventListener("input", apply));
  $("prev").addEventListener("click", () => { page--; draw(); });
  $("next").addEventListener("click", () => { page++; draw(); });
  apply();
}

/* Forecast */
function renderForecast(F, s) {
  const svg = document.getElementById("wape");
  const rows = [...F.metrics].sort((a, b) => b.wape - a.wape);
  const best = Math.min(...rows.map(r => r.wape));
  const W = 560, rowH = 58, m = { l: 200, r: 70, t: 8, b: 8 }, H = m.t + rows.length * rowH + m.b;
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  const x = linear(0, Math.max(...rows.map(r => r.wape)) * 1.05, m.l, W - m.r);
  rows.forEach((r, i) => {
    const yy = m.t + i * rowH;
    const top = r.wape === best;
    el("text", { x: m.l - 12, y: yy + rowH / 2 + 5, "text-anchor": "end", "font-size": 14, fill: C.ink }, svg, r.model);
    el("rect", { x: m.l, y: yy + 10, width: x(r.wape) - m.l, height: rowH - 20, fill: top ? C.yellow : C.gray,
      stroke: top ? C.ink : "none", "stroke-width": 1.5 }, svg);
    el("text", { x: x(r.wape) + 8, y: yy + rowH / 2 + 5, "font-size": 14, "font-weight": 600, fill: C.ink }, svg, fmt.pct1(r.wape));
  });
  el("line", { x1: m.l, x2: m.l, y1: 0, y2: H, stroke: C.ink, "stroke-width": 1.5 }, svg);
  const t = document.getElementById("forecast-table");
  t.innerHTML = `<thead><tr><th>Model</th><th>WAPE</th><th>MAE</th><th>RMSE</th></tr></thead><tbody>` +
    rows.map(r => `<tr class="${r.wape === best ? "best" : ""}"><td>${esc(r.model)}</td><td>${fmt.pct1(r.wape)}</td>` +
      `<td>${r.mae.toFixed(2)}</td><td>${r.rmse.toFixed(2)}</td></tr>`).join("") + "</tbody>";
  const f = s.forecast, sp = f.splits;
  const day = iso => new Date(iso);
  const span = (a, b) => { const d0 = day(a), d1 = new Date(day(b) - 864e5); return `${MONTHS[d0.getMonth()]} ${d0.getDate()}–${d1.getDate()}`; };
  document.getElementById("forecast-protocol").textContent =
    `Target: trips starting in each taxi zone in the next hour. Train ${span(sp.feature_start, sp.train_end)}, ` +
    `validate ${span(sp.train_end, sp.validation_end)}, test ${span(sp.validation_end, sp.test_end)} ` +
    `(${fmt.int(f.split_rows.test)} zone-hours). The first week only feeds the lag features. ` +
    `Model: ${f.model.name} with ${f.model.loss} loss and ${f.features} past-only features (lags of ${f.lags.join(", ")} hours, ` +
    `rolling means, calendar). The model is fixed after validation; later observed outcomes update its lags. ` +
    `WAPE = Σ|error| / Σ actual. Single-month development evaluation.`;
}

/* Data quality */
function renderQuality(Q, s) {
  document.getElementById("dropped-share").textContent = fmt.pct2(1 - s.retention);
  const svg = document.getElementById("quality-chart");
  const groups = [["Excluded by default", Q.flags.filter(f => f.excluded)],
                  ["Flagged for review, kept", Q.flags.filter(f => !f.excluded)]];
  const rowH = 30, W = 1000, m = { l: 300, r: 170 };
  const H = groups.reduce((a, [, g]) => a + 40 + g.length * rowH, 0) + 10;
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  const max = Math.max(...Q.flags.map(f => f.records));
  const x = linear(0, max, m.l, W - m.r);
  let yy = 0;
  groups.forEach(([title, rows]) => {
    el("text", { x: 0, y: yy + 26, "font-size": 15, "font-weight": 600, fill: C.ink }, svg, title);
    yy += 40;
    rows.sort((a, b) => b.records - a.records).forEach(f => {
      el("text", { x: m.l - 12, y: yy + rowH / 2 + 5, "text-anchor": "end", "font-size": 14, fill: C.ink }, svg, f.label);
      el("rect", { x: m.l, y: yy + 6, width: Math.max(f.records ? 2 : 0, x(f.records) - m.l), height: rowH - 12,
        fill: f.excluded ? C.ink : C.gray }, svg);
      el("text", { x: Math.max(x(f.records), m.l) + 8, y: yy + rowH / 2 + 5, "font-size": 13.5, fill: C.ink2 }, svg,
        `${fmt.int(f.records)} · ${fmt.pct(f.share)}`);
      yy += rowH;
    });
  });
}

function renderSources(s) {
  document.getElementById("src-page").href = s.source_page;
  document.getElementById("src-dict").href = s.dictionary_url;
  document.getElementById("sources").innerHTML = s.sources.map(f =>
    `<li><a href="${esc(f.url)}">${esc(f.file)}</a>${f.bytes ? ` · ${f.bytes >= 1e6 ? (f.bytes / 1e6).toFixed(1) + " MB" : Math.ceil(f.bytes / 1e3) + " KB"}` : ""} · SHA-256 ${esc(f.sha256)}</li>`).join("");
}

async function main() {
  const names = ["summary", "zones", "boroughs", "time", "rules", "forecast", "quality"];
  const data = Object.fromEntries(await Promise.all(names.map(async n => {
    const res = await fetch(`data/${n}.json`);
    if (!res.ok) throw new Error(`data/${n}.json: ${res.status}`);
    return [n, await res.json()];
  })));
  const s = data.summary;
  bindValues(data);
  const tasks = [
    () => renderFunnel(s), () => renderMap(data.zones, s), () => renderMatrix(data.boroughs),
    () => renderHourly(data.time, s), () => renderDaily(data.time), () => renderHighlights(data.rules),
    () => renderExplorer(data.rules), () => renderForecast(data.forecast, s), () => renderQuality(data.quality, s),
    () => renderSources(s),
  ];
  for (const t of tasks) {
    try { t(); } catch (err) { console.error(err); }
  }
}
main().catch(err => {
  console.error(err);
  document.getElementById("main").prepend(h("p", { class: "wrap note" },
    "The data files could not be loaded. If you opened this file directly, serve the folder over HTTP (see README)."));
});
